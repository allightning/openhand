function rows(id: string, lines: string[]): string[] {
  const w = lines[0]?.length ?? 0;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i].length !== w) {
      throw new Error(`${id} row ${i} width ${lines[i].length}, expected ${w}`);
    }
  }
  return lines;
}

