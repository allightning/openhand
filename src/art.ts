export function cardSeal(kind: string): string {
  if (kind === "strike" || kind === "strike2") {
    return `<svg viewBox="0 0 100 70" class="seal"><path d="M18 50 L50 12 L82 50 L68 50 L50 28 L32 50 Z" fill="currentColor"/></svg>`;
  }
  if (kind === "defend" || kind === "defend2") {
    return `<svg viewBox="0 0 100 70" class="seal"><path d="M50 10 L82 28 L82 48 L50 66 L18 48 L18 28 Z" fill="none" stroke="currentColor" stroke-width="5"/></svg>`;
  }
  if (kind === "push" || kind === "push2") {
    return `<svg viewBox="0 0 100 70" class="seal"><path d="M12 35 H58 M48 18 L72 35 L48 52" fill="none" stroke="currentColor" stroke-width="6" stroke-linejoin="miter"/></svg>`;
  }
  if (kind === "charge" || kind === "charge2") {
    return `<svg viewBox="0 0 100 70" class="seal"><circle cx="50" cy="36" r="16" fill="none" stroke="currentColor" stroke-width="5"/><circle cx="50" cy="36" r="6" fill="currentColor"/></svg>`;
  }
  if (kind === "drawcut") {
    return `<svg viewBox="0 0 100 70" class="seal"><path d="M22 52 L70 18 L74 24 L28 58 Z" fill="currentColor"/><rect x="18" y="48" width="16" height="6" fill="currentColor"/></svg>`;
  }
  if (kind === "backpalm") {
    return `<svg viewBox="0 0 100 70" class="seal"><path d="M78 35 H32 M42 18 L18 35 L42 52" fill="none" stroke="currentColor" stroke-width="6"/></svg>`;
  }
  if (kind === "split") {
    return `<svg viewBox="0 0 100 70" class="seal"><rect x="46" y="12" width="8" height="46" fill="currentColor"/><path d="M28 28 L72 52 M72 28 L28 52" stroke="currentColor" stroke-width="5"/></svg>`;
  }
  if (kind === "close") {
    return `<svg viewBox="0 0 100 70" class="seal"><circle cx="28" cy="36" r="10" fill="currentColor"/><circle cx="72" cy="36" r="10" fill="none" stroke="currentColor" stroke-width="5"/></svg>`;
  }
  if (kind === "elbow") {
    return `<svg viewBox="0 0 100 70" class="seal"><path d="M22 50 L50 14 L78 50" fill="none" stroke="currentColor" stroke-width="6"/><circle cx="50" cy="50" r="8" fill="currentColor"/></svg>`;
  }
  if (kind === "sweep") {
    return `<svg viewBox="0 0 100 70" class="seal"><path d="M18 48 Q50 12 82 48" fill="none" stroke="currentColor" stroke-width="6"/></svg>`;
  }
  return `<svg viewBox="0 0 100 70" class="seal"><path d="M30 50 L50 18 L70 50" fill="none" stroke="currentColor" stroke-width="5"/></svg>`;
}

